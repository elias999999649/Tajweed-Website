export function getRuleBySlug(slug: string) {
  return tajweedRules.find((rule) => rule.slug === slug);
}

export function getRulesByCategory(category: string) {
  return tajweedRules.filter((rule) => rule.category === category);
}

export function getVerifiedRules() {
  return tajweedRules.filter((rule) => rule.verificationStatus === "verified");
}

export function getReviewRequiredRules() {
  return tajweedRules.filter((rule) => rule.verificationStatus === "needs_review");
}
